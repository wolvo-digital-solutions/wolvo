/**
 * Copies the official brand marks used in the "Our Tech Stack" section from
 * the simple-icons package (CC0 path data) into src/data/techLogos.ts, so the
 * app ships only the handful of paths it needs.
 *
 *   npm run logos
 *
 * To add a tool: add its simple-icons slug below, run `npm run logos`, then
 * reference the slug from src/data/techStack.ts. Brand marks remain trademarks
 * of their owners and are shown only to name the tools Wolvo works with.
 * (Adobe's app icons are not distributed by simple-icons at Adobe's request,
 * so Adobe tools are listed by name only.)
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as icons from 'simple-icons';

const SLUGS = [
  'react',
  'nextdotjs',
  'typescript',
  'nodedotjs',
  'vite',
  'astro',
  'gsap',
  'postgresql',
  'stripe',
  'sanity',
  'supabase',
  'firebase',
  'android',
  'apple',
  'googlemaps',
  'davinciresolve',
  'figma',
];

const bySlug = new Map(Object.values(icons).filter((i) => i && i.slug).map((i) => [i.slug, i]));
const entries = SLUGS.map((slug) => {
  const icon = bySlug.get(slug);
  if (!icon) throw new Error(`simple-icons has no "${slug}"`);
  return `  ${JSON.stringify(slug)}: { title: ${JSON.stringify(icon.title)}, path: ${JSON.stringify(icon.path)} },`;
});

const file = `/* Generated by scripts/extract-logos.mjs from simple-icons — do not edit by hand. */

export interface TechLogo {
  title: string;
  /** SVG path data for a 24×24 viewBox (official mark, single colour). */
  path: string;
}

export const techLogos = {
${entries.join('\n')}
} as const satisfies Record<string, TechLogo>;

export type TechLogoId = keyof typeof techLogos;
`;

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
writeFileSync(path.join(root, 'src', 'data', 'techLogos.ts'), file);
console.log(`✓ ${SLUGS.length} logos → src/data/techLogos.ts`);
